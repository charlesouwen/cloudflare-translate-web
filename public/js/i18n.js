/* 当前语言 */
window.__currentLocale = localStorage.getItem(I18N_KEY) || navigator.language || 'zh-CN';
if (!LOCALES[window.__currentLocale]) {
  /* 回退到最接近的语言 */
  if (window.__currentLocale.startsWith('zh')) window.__currentLocale = 'zh-CN';
  else if (window.__currentLocale.startsWith('ja')) window.__currentLocale = 'ja';
  else window.__currentLocale = 'en';
}

/* 翻译函数 */
function __t(key, params) {
  const locale = LOCALES[window.__currentLocale] || LOCALES['en'];
  let text = locale[key] || LOCALES['en'][key] || key;
  if (params) {
    Object.keys(params).forEach(k => {
      text = text.replace(`{${k}}`, params[k]);
    });
  }
  return text;
}
window.__t = __t;

/* 切换界面语言 */
function setUILanguage(lang) {
  if (!LOCALES[lang]) return;
  window.__currentLocale = lang;
  localStorage.setItem(I18N_KEY, lang);
  applyI18n();
}

/* 应用 i18n 到 DOM */
function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = __t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = __t(key);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = __t(key);
  });
  document.title = __t('appTitle') + ' - Translate';
}

